'use strict';

/**
 * Regenerate docs/api-transcript.md from a real running server.
 *
 * Boots an ephemeral MongoDB, starts `server.js` as a child process exactly as
 * production would, and replays a scripted session against it over HTTP. Every
 * status line and body in the generated document is a real response — nothing
 * in it is written by hand.
 *
 * It also rewrites the excerpts between the `captured-output` markers in
 * README.md from the same run, so the README cannot drift away from the
 * evidence it cites.
 *
 *   npm run capture:transcript
 */

const { spawn } = require('node:child_process');
const fs = require('node:fs/promises');
const path = require('node:path');

const { MongoMemoryServer } = require('mongodb-memory-server');

const PORT = Number(process.env.CAPTURE_PORT || 8980);
const BASE = `http://127.0.0.1:${PORT}`;
const OUTPUT = path.join(__dirname, '..', 'docs', 'api-transcript.md');
const README = path.join(__dirname, '..', 'README.md');

/** Exchanges quoted in the README, with the heading shown above each. */
const README_EXCERPTS = [
  ['The public catalogue, anonymous and paginated', 'The public catalogue, no authentication'],
  ['The same listing as XML, selected by the request headers', 'The same listing as XML'],
  ['The editorial policy the brief asks for', 'Darth Vader is refused publication'],
];

const transcript = [];

function redact(value) {
  if (typeof value !== 'string') return value;
  return value.replace(/(eyJ[\w-]+\.[\w-]+\.)[\w-]+/g, '$1<signature>');
}

async function call(label, method, url, { token, body, headers = {} } = {}) {
  const requestHeaders = { ...headers };
  if (body !== undefined) requestHeaders['Content-Type'] = 'application/json';
  if (token) requestHeaders.Authorization = `Bearer ${token}`;

  const response = await fetch(`${BASE}${url}`, {
    method,
    headers: requestHeaders,
    body: body === undefined ? undefined : JSON.stringify(body),
  });

  const contentType = response.headers.get('content-type') || '';
  const isJson = contentType.includes('application/json');
  const raw = await response.text();
  const parsed = isJson && raw ? JSON.parse(raw) : raw;

  transcript.push({
    label,
    method,
    url,
    requestHeaders,
    requestBody: body,
    status: response.status,
    contentType,
    body: parsed,
  });

  return parsed;
}

function render() {
  const lines = [
    '# Wookie Books — captured API session',
    '',
    'Generated by `npm run capture:transcript`, which starts an ephemeral MongoDB,',
    'runs `node server.js`, and replays the session below over real HTTP.',
    'Bearer token signatures are truncated; nothing else is edited.',
    '',
  ];

  for (const entry of transcript) {
    lines.push(`## ${entry.label}`, '');
    lines.push('```http');
    lines.push(`${entry.method} ${entry.url}`);
    for (const [key, value] of Object.entries(entry.requestHeaders)) {
      lines.push(`${key}: ${redact(value)}`);
    }
    if (entry.requestBody !== undefined) {
      lines.push('', JSON.stringify(entry.requestBody, null, 2));
    }
    lines.push('```', '');
    lines.push('```http');
    lines.push(`HTTP/1.1 ${entry.status}`);
    lines.push(`Content-Type: ${entry.contentType}`);
    if (entry.body !== '') {
      const rendered =
        typeof entry.body === 'string' ? entry.body : JSON.stringify(entry.body, null, 2);
      lines.push('', redact(rendered));
    }
    lines.push('```', '');
  }

  return lines.join('\n');
}

function renderExcerpts() {
  const lines = [
    '<!-- captured-output:start (generated by npm run capture:transcript — do not edit by hand) -->',
    '',
  ];

  for (const [heading, label] of README_EXCERPTS) {
    const entry = transcript.find((item) => item.label === label);
    if (!entry) throw new Error(`No captured exchange labelled "${label}"`);

    lines.push(`**${heading}**`, '', '```http');
    lines.push(`${entry.method} ${entry.url}`);
    for (const [key, value] of Object.entries(entry.requestHeaders)) {
      lines.push(`${key}: ${redact(value)}`);
    }
    if (entry.requestBody !== undefined) {
      lines.push('', JSON.stringify(entry.requestBody, null, 2));
    }
    lines.push('```', '', '```http');
    lines.push(`HTTP/1.1 ${entry.status}`, `Content-Type: ${entry.contentType}`);
    const rendered =
      typeof entry.body === 'string' ? entry.body : JSON.stringify(entry.body, null, 2);
    lines.push('', redact(rendered), '```', '');
  }

  lines.push('<!-- captured-output:end -->');
  return lines.join('\n');
}

async function syncReadme() {
  const readme = await fs.readFile(README, 'utf8');
  const pattern = /<!-- captured-output:start[\s\S]*?<!-- captured-output:end -->/;
  if (!pattern.test(readme)) {
    throw new Error('README.md is missing the captured-output markers');
  }
  await fs.writeFile(README, readme.replace(pattern, renderExcerpts()), 'utf8');
}

async function waitForHealth(attempts = 60) {
  for (let i = 0; i < attempts; i += 1) {
    try {
      const response = await fetch(`${BASE}/api/health`);
      if (response.ok) return;
    } catch {
      /* server not up yet */
    }
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  throw new Error(`Server did not become healthy on ${BASE}`);
}

async function session() {
  await call('Health check', 'GET', '/api/health');

  await call('Register an author', 'POST', '/api/users', {
    body: {
      name: 'Lohgarra',
      username: 'lohgarra',
      authorPseudonym: 'Lohgarra of Kashyyyk',
      password: 'a-very-long-passphrase',
    },
  });

  const login = await call('Authenticate and receive a JWT', 'POST', '/api/auth/login', {
    body: { username: 'lohgarra', password: 'a-very-long-passphrase' },
  });
  const token = login.data.jwt;

  const created = await call('Create a book (defaults to draft)', 'POST', '/api/me/books', {
    token,
    body: {
      title: 'Adventures on Kashyyyk',
      description: 'Life among the wroshyr trees, told by one who climbed them.',
      coverImageUrl: 'https://example.test/covers/kashyyyk.png',
      price: 14.99,
    },
  });
  const bookId = created.data.id;

  await call('A draft is invisible to the public catalogue', 'GET', '/api/books');

  await call('Publish the book', 'PUT', `/api/me/books/${bookId}`, {
    token,
    body: { status: 'published' },
  });

  await call('The public catalogue, no authentication', 'GET', '/api/books?sort=newest');

  await call('Search the catalogue', 'GET', '/api/books?search=wroshyr');

  await call('The same listing as XML', 'GET', '/api/books', {
    headers: { Accept: 'application/xml' },
  });

  await call('Unpublish (DELETE on the author resource)', 'DELETE', `/api/me/books/${bookId}`, {
    token,
  });

  await call('The listing is gone from the catalogue', 'GET', '/api/books');

  await call('...but the author still has the manuscript', 'GET', '/api/me/books', { token });

  const vader = await call('Register Darth Vader', 'POST', '/api/users', {
    body: {
      name: 'Anakin Skywalker',
      username: 'vader',
      authorPseudonym: 'Darth Vader',
      password: 'the-dark-side-is-a-pathway',
    },
  });
  if (!vader.data) throw new Error('Darth Vader registration failed unexpectedly');

  const vaderLogin = await call('Darth Vader authenticates', 'POST', '/api/auth/login', {
    body: { username: 'vader', password: 'the-dark-side-is-a-pathway' },
  });

  await call('Darth Vader is refused publication', 'POST', '/api/me/books', {
    token: vaderLogin.data.jwt,
    body: {
      title: 'My Rise to Power',
      description: 'A memoir.',
      coverImageUrl: 'https://example.test/covers/vader.png',
      price: 99.99,
      status: 'published',
    },
  });

  await call('Authors cannot touch each other books', 'PUT', `/api/me/books/${bookId}`, {
    token: vaderLogin.data.jwt,
    body: { title: 'Mine now' },
  });

  await call('An unauthenticated write is rejected', 'POST', '/api/me/books', {
    body: { title: 'x' },
  });
}

async function main() {
  const mongod = await MongoMemoryServer.create({ binary: { version: '8.2.6' } });

  const server = spawn(process.execPath, ['server.js'], {
    cwd: path.join(__dirname, '..'),
    env: {
      ...process.env,
      ENVIRONMENT: 'production',
      SERVER_PORT: String(PORT),
      DATABASE_URL: `${mongod.getUri()}wookie-books-demo`,
      JWT_SECRET_KEY: 'transcript-capture-key-not-for-production',
      BCRYPT_ROUNDS: '10',
    },
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  try {
    await waitForHealth();
    await session();
    await fs.mkdir(path.dirname(OUTPUT), { recursive: true });
    await fs.writeFile(OUTPUT, `${render()}\n`, 'utf8');
    await syncReadme();
    process.stdout.write(
      `Wrote ${OUTPUT} (${transcript.length} exchanges) and refreshed the README excerpts\n`
    );
  } finally {
    server.kill('SIGTERM');
    await mongod.stop();
  }
}

main().catch((error) => {
  process.stderr.write(`${error.stack}\n`);
  process.exitCode = 1;
});
